#!/usr/bin/env python3
"""Build or refresh .claude/map.md — a component map of the repo — and the index block in CLAUDE.md.

Usage:  python build_map.py [repo_root]
Re-running is safe: Purpose/Links lines, file descriptions and the Problem routing table
written by Claude or the user are kept; only the file lists and symbols are regenerated.
"""
import os
import re
import subprocess
import sys

MAP = os.path.join(".claude", "map.md")
CODE_EXT = {".py", ".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx", ".vue", ".go", ".rs", ".java",
            ".kt", ".rb", ".php", ".cs", ".swift", ".dart", ".sql", ".sh", ".mq5", ".mqh"}
CONF_EXT = {".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".env.example", ".html", ".css", ".scss"}
SKIP_DIRS = {".git", "node_modules", "dist", "build", ".next", ".nuxt", "out", "coverage", "venv",
             ".venv", "env", "__pycache__", ".pytest_cache", ".mypy_cache", ".idea", ".vscode",
             ".claude", "vendor", "target", ".turbo", ".cache", "logs", "data"}
SKIP_FILES = re.compile(r"(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|poetry\.lock|\.min\.(js|css)$|\.map$)")
MAX_FILES_PER_COMPONENT = 60
MAX_SYMBOLS = 8

SYMBOL_RES = {
    "py": [re.compile(r"^(?:async\s+)?def\s+(\w+)"), re.compile(r"^class\s+(\w+)")],
    "js": [re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?function\s*\*?\s*(\w+)"),
           re.compile(r"^export\s+(?:default\s+)?class\s+(\w+)"),
           re.compile(r"^export\s+(?:const|let|var)\s+(\w+)"),
           re.compile(r"^(?:async\s+)?function\s+(\w+)"),
           re.compile(r"^(?:router|app)\.(get|post|put|patch|delete)\(\s*['\"]([^'\"]+)")],
    "go": [re.compile(r"^func\s+(?:\([^)]*\)\s*)?(\w+)"), re.compile(r"^type\s+(\w+)")],
    "mq": [re.compile(r"^\w[\w\s\*&]*\s+(\w+)\s*\([^;]*$")],
}
LANG = {".py": "py", ".js": "js", ".mjs": "js", ".cjs": "js", ".ts": "js", ".tsx": "js",
        ".jsx": "js", ".vue": "js", ".go": "go", ".mq5": "mq", ".mqh": "mq"}


def list_files(root):
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                             cwd=root, capture_output=True, text=True, timeout=20)
        if out.returncode == 0:
            files = out.stdout.splitlines()
        else:
            raise RuntimeError
    except Exception:
        files = []
        for d, dirs, names in os.walk(root):
            dirs[:] = [x for x in dirs if x not in SKIP_DIRS and not x.startswith(".")]
            files += [os.path.relpath(os.path.join(d, n), root) for n in names]
    keep = []
    for f in files:
        f = f.replace("\\", "/")
        parts = f.split("/")
        if any(p in SKIP_DIRS for p in parts[:-1]) or SKIP_FILES.search(f):
            continue
        ext = os.path.splitext(f)[1].lower()
        if ext in CODE_EXT or ext in CONF_EXT or parts[-1] in ("Dockerfile", "Makefile"):
            if os.path.isfile(os.path.join(root, f)):
                keep.append(f)
    return sorted(keep)


def group_components(files, max_size=15, max_depth=4):
    """Group by top folder, then split any group larger than max_size by its next folder level."""
    def key(path, depth):
        parts = path.split("/")[:-1]
        return "/".join(parts[:depth]) if parts else "(root)"

    groups = {}
    for f in files:
        groups.setdefault(key(f, 1), []).append(f)
    depth = 1
    while depth < max_depth:
        changed = False
        nxt = {}
        for name, flist in groups.items():
            here = name.count("/") + 1
            subs = {key(f, depth + 1) for f in flist}
            if name != "(root)" and here == depth and len(flist) > max_size and len(subs) > 1:
                for f in flist:
                    nxt.setdefault(key(f, depth + 1), []).append(f)
                changed = True
            else:
                nxt.setdefault(name, []).extend(flist)
        groups = nxt
        depth += 1
        if not changed:
            break
    return groups


FOLD_RULES = [
    ("CI / tooling config", re.compile(r"^\.(github|gitlab|circleci|husky|devcontainer|agents)/")),
    ("database migrations", re.compile(r"(^|/)(migrations|alembic/versions|migrate)/")),
    ("test fixtures / snapshots", re.compile(r"(^|/)(fixtures|__snapshots__|snapshots)/")),
]
GENERATED_RX = re.compile(r"(auto-?generated|generated by|do not edit|@generated)", re.I)


def fold_reason(root, path):
    for label, rx in FOLD_RULES:
        if rx.search(path):
            return label
    try:
        with open(os.path.join(root, path), encoding="utf-8", errors="ignore") as fh:
            head = fh.read(400)
        if GENERATED_RX.search(head):
            return "generated code"
    except Exception:
        pass
    return None


def symbols(root, path):
    lang = LANG.get(os.path.splitext(path)[1].lower())
    if not lang:
        return []
    found = []
    try:
        with open(os.path.join(root, path), encoding="utf-8", errors="ignore") as fh:
            for line in fh:
                for rx in SYMBOL_RES[lang]:
                    m = rx.match(line)
                    if m:
                        g = m.groups()
                        name = f"{g[0].upper()} {g[1]}" if len(g) == 2 else g[0]
                        if (name not in found and not name.startswith("_")
                                and name not in ("if", "for", "while", "switch", "return", "else")):
                            found.append(name)
                        break
                if len(found) >= MAX_SYMBOLS:
                    break
    except Exception:
        pass
    return found


def size_tokens(root, files):
    total = 0
    for f in files:
        try:
            total += os.path.getsize(os.path.join(root, f))
        except OSError:
            pass
    return total // 4


def parse_existing(text):
    """Keep what Claude/user wrote: routing table, Purpose/Links per component, file descriptions."""
    routing, comp_notes, file_desc = None, {}, {}
    m = re.search(r"## Problem routing\n(.*?)(?=\n## Components)", text, re.S)
    if m:
        routing = m.group(1).strip("\n")
    current = None
    for line in text.splitlines():
        h = re.match(r"^### (.+?)\s+\(\d+ files?\)", line)
        if h:
            current = h.group(1)
            comp_notes[current] = []
            continue
        if current and re.match(r"^(Purpose|Links):", line):
            comp_notes[current].append(line)
        fm = re.match(r"^- `([^`]+)` — (.*?)(?: · .*)?$", line)
        if fm and fm.group(2).strip() and fm.group(2).strip() != "TODO":
            file_desc[fm.group(1)] = fm.group(2).strip()
    return routing, comp_notes, file_desc


DEFAULT_ROUTING = """Map a symptom or task to where to start. Add a row every time a problem gets solved.

| Symptom / task | Component | Start at |
|---|---|---|
| TODO e.g. "orders not closing" | TODO | `path/file` → `function()` |"""


def build(root):
    files = list_files(root)
    folded, kept = {}, []
    for f in files:
        reason = fold_reason(root, f)
        if reason:
            folder = os.path.dirname(f) or "(root)"
            folded.setdefault((reason, folder), 0)
            folded[(reason, folder)] += 1
        else:
            kept.append(f)
    comps = group_components(kept)

    map_path = os.path.join(root, MAP)
    old = open(map_path, encoding="utf-8").read() if os.path.exists(map_path) else ""
    routing, comp_notes, file_desc = parse_existing(old)

    out = []
    for name in sorted(comps, key=lambda c: (c == "(root)", c)):
        flist = comps[name]
        out.append(f"### {name}  ({len(flist)} file{'s' if len(flist) != 1 else ''})")
        notes = comp_notes.get(name) or ["Purpose: TODO", "Links: uses TODO · used by TODO"]
        out += notes
        for f in flist[:MAX_FILES_PER_COMPONENT]:
            syms = symbols(root, f)
            line = f"- `{f}` — {file_desc.get(f, 'TODO')}"
            if syms:
                line += " · " + ", ".join(f"`{s}`" for s in syms)
            out.append(line)
        if len(flist) > MAX_FILES_PER_COMPONENT:
            out.append(f"- … +{len(flist) - MAX_FILES_PER_COMPONENT} more files (grep inside `{name}/`)")
        out.append("")

    if folded:
        out.append("### Folded (not listed — open only if the task is about them)")
        by_reason = {}
        for (reason, folder), n in sorted(folded.items()):
            by_reason.setdefault(reason, []).append(f"`{folder}/` ({n})")
        for reason, dirs in by_reason.items():
            shown = ", ".join(dirs[:8]) + (f", +{len(dirs) - 8} more" if len(dirs) > 8 else "")
            out.append(f"- {reason}: {shown}")
        out.append("")
    body = "\n".join(out)
    repo_tok = size_tokens(root, files)
    header = (
        "# Component map\n"
        "<!-- Generated by build_map.py. Edit Purpose/Links lines, file descriptions and the routing\n"
        "     table freely: they are kept on refresh. Read ONE component section at a time. -->\n\n"
    )
    doc = header + "## Problem routing\n" + (routing or DEFAULT_ROUTING) + "\n\n## Components\n" + body
    map_tok = len(doc) // 4
    stats = f"Repo source ≈ {repo_tok:,} tokens · {len(files)} files · this map ≈ {map_tok:,} tokens\n\n"
    doc = doc.replace("## Problem routing\n", stats + "## Problem routing\n", 1)

    os.makedirs(os.path.dirname(map_path), exist_ok=True)
    with open(map_path, "w", encoding="utf-8") as fh:
        fh.write(doc)

    update_index(root, comps, comp_notes)
    pct = (1 - map_tok / repo_tok) * 100 if repo_tok else 0
    todo = doc.count("TODO")
    print(f"Wrote {MAP}: {len(comps)} components, {len(files)} files.")
    print(f"Repo source ≈ {repo_tok:,} tokens → map ≈ {map_tok:,} tokens ({pct:.0f}% smaller).")
    print(f"{todo} TODO placeholders left to describe." if todo else "No TODOs left.")


def update_index(root, comps, comp_notes):
    """Write a compact component index into CLAUDE.md between markers (always loaded)."""
    cm = os.path.join(root, "CLAUDE.md")
    if not os.path.exists(cm):
        return
    rows = ["| Component | Files | Purpose |", "|---|---|---|"]
    for name in sorted(comps, key=lambda c: (c == "(root)", c)):
        purpose = "TODO"
        for n in comp_notes.get(name, []):
            if n.startswith("Purpose:"):
                purpose = n[len("Purpose:"):].strip() or "TODO"
        rows.append(f"| `{name}` | {len(comps[name])} | {purpose} |")
    block = ("<!-- map-index:start -->\n"
             "Details per component: `.claude/map.md` (read only the section you need).\n\n"
             + "\n".join(rows) + "\n<!-- map-index:end -->")
    text = open(cm, encoding="utf-8").read()
    if "<!-- map-index:start -->" in text:
        text = re.sub(r"<!-- map-index:start -->.*?<!-- map-index:end -->", lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n## Component index\n" + block + "\n"
    with open(cm, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    build(os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "."))
